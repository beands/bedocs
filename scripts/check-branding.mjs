#!/usr/bin/env node
/**
 * check-branding.mjs — verifies that user-facing strings reference BeDocs,
 * not Blume. Scans source files for common Blume references that should
 * have been replaced during the fork. Internal type names (BlumeConfig,
 * BlumeError, etc.) and CSS variables (--blume-*) are intentionally
 * excluded — they stay aligned with upstream for merge compatibility.
 */

import { readdir, readFile } from "node:fs/promises";
import { join, relative } from "node:path";

const ROOT = new URL("..", import.meta.url).pathname.replace(/^\//, "");

// Patterns that should NOT appear in user-facing strings.
// Matches "Blume" or "blume" in contexts visible to users:
// - CLI output, error messages, generated file headers, docs URLs.
// Does NOT flag internal identifiers (BlumeConfig, BLUME_SRC, etc.).
const FORBIDDEN_PATTERNS = [
  /useblume\.dev/g, // Old docs URL
  /"blume /g, // CLI command name in strings
  /`blume /g, // CLI command name in template literals
  / blume build`/g, // CLI command references
  / blume dev`/g,
  / blume eject`/g,
  / blume init`/g,
  / blume check`/g,
  / blume validate`/g,
  / blume doctor`/g,
  / blume sync`/g,
  / blume add`/g,
  / blume preview`/g,
  / blume audit`/g,
  / blume translate`/g,
  /BLUME_RUNTIME_DIR/g, // Old env var
  /Generated by Blume/g, // Generated file headers
];

// Directories to skip (internal, vendored, or generated).
const SKIP_DIRS = new Set([
  "node_modules",
  ".git",
  "dist",
  ".bedocs",
  ".blume",
  ".turbo",
  ".next",
  ".vercel",
  "coverage",
  "scripts",
  "skills",
]);

// File extensions to scan.
const SCAN_EXTENSIONS = new Set([
  ".ts",
  ".tsx",
  ".astro",
  ".mjs",
  ".js",
  ".json",
  ".md",
  ".yml",
  ".yaml",
]);

const violations = [];

async function* walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  for (const entry of entries) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) {
      if (!SKIP_DIRS.has(entry.name)) {
        yield* walk(path);
      }
    } else if (entry.isFile()) {
      const ext = entry.name.slice(entry.name.lastIndexOf("."));
      if (SCAN_EXTENSIONS.has(ext)) {
        yield path;
      }
    }
  }
}

for await (const file of walk(ROOT)) {
  const content = await readFile(file, "utf-8");
  for (const pattern of FORBIDDEN_PATTERNS) {
    const matches = content.match(pattern);
    if (matches) {
      for (const match of matches) {
        violations.push({ file: relative(ROOT, file), match });
      }
    }
  }
}

if (violations.length > 0) {
  console.error(`\n❌ Branding check failed: found ${violations.length} forbidden Blume reference(s).\n`);
  for (const { file, match } of violations) {
    console.error(`  ${file}: "${match}"`);
  }
  console.error("\nThese should be replaced with BeDocs equivalents.");
  process.exit(1);
} else {
  console.log("✅ Branding check passed: no forbidden Blume references found.");
}
